export function clone(value) { return JSON.parse(JSON.stringify(value)); }
export function newProvider(id) {
  const item = catalog.find(item => item.id === id);
  if (!item) throw new Error("Choose a provider from the list");
  return {provider: id, source: item.defaultSource, enabled: true, account: "",
    accountIndex: 0, allAccounts: false, apiKey: "", includeCost: true};
}
export function providerRows(settings, detected) {
  if (Array.isArray(settings.providerConfigs)) return clone(settings.providerConfigs);
  const ids = Array.isArray(settings.providers) && settings.providers.length ? settings.providers
    : settings.provider && settings.provider !== "all" ? [settings.provider] : detected;
  return (ids || ["codex"]).map(id => {
    const known = catalog.find(item => item.id === id);
    return known ? newProvider(id) : {provider: String(id), source: "auto", enabled: true};
  });
}
export function sources(provider) {
  return (catalog.find(item => item.id === provider)?.sources || ["auto"])
    .map(value => ({value, label: provider === "claude" && value === "api" ? "Admin API key" : provider === "bedrock" && value === "api" ? "AWS credentials" : ({auto: "Automatic", cli: "CLI account", oauth: "OAuth account",
      native: "Linux helper", "native-auth": "Browser login", api: "API key", web: "Web account", local: "Local demo"})[value] || value}));
}
export function validate(patch) {
  if (!patch || typeof patch !== "object" || Array.isArray(patch)) throw new Error("Invalid settings");
  for (const [key, min, max] of [["refreshIntervalSeconds",60,86400],["timeoutSeconds",5,300],
    ["costRefreshIntervalSeconds",300,604800],["providerRetryAttempts",1,4],
    ["failureCooldownSeconds",30,3600],["costScanTimeoutSeconds",60,1800],
    ["cardBars",1,6],["expandedRows",0,8]]) {
    if (patch[key] !== undefined && (!Number.isInteger(patch[key]) || patch[key] < min || patch[key] > max))
      throw new Error("Check the value for " + key);
  }
  for (const key of ["includeStatus", "shareProviderFetches"]) {
    if (patch[key] !== undefined && typeof patch[key] !== "boolean")
      throw new Error("Check the value for " + key);
  }
  if (patch.paceIndicatorStyle !== undefined && !["position", "bar", "provider", "theme", "gaps", "off"].includes(patch.paceIndicatorStyle))
    throw new Error("Choose a pace indicator style");
  if (patch.providerConfigs !== undefined) {
    if (!Array.isArray(patch.providerConfigs)) throw new Error("Invalid provider list");
    for (const row of patch.providerConfigs) {
      const item = catalog.find(item => item.id === row.provider);
      if (!item) throw new Error("Remove the unknown provider: " + String(row.provider || ""));
      if (!item.sources.includes(row.source)) throw new Error("Choose a source for " + item.name);
      if (!Number.isInteger(Number(row.accountIndex || 0)) || Number(row.accountIndex || 0) < 0)
        throw new Error("Check the account index for " + item.name);
    }
  }
  return patch;
}
